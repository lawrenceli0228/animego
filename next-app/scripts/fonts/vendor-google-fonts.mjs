#!/usr/bin/env node
// vendor-google-fonts.mjs — writes the site's webfonts into the repository.
//
// The fonts used to come from next/font/google, which downloads them from
// Google while the app compiles. When that download failed, `next dev`
// answered 500 on every page for the rest of its life ("Can't resolve
// '@vercel/turbopack-next/internal/font/google/font'"), and a production
// build could fail the same way. This script runs next/font/google's own
// loader once, with the same options the layout used to pass, and commits
// what it produces:
//
//   public/fonts/<family>-<sha256 prefix>.woff2   the font files
//   src/app/fonts.css                             their @font-face rules
//   src/app/fontPreloads.ts                       the files to preload
//
// Same files, same @font-face descriptors and unicode-range subsets, same
// preloads as next/font/google produced — only now nothing is fetched at
// build time. File names carry a content hash, so they are served with an
// immutable Cache-Control (next.config.ts headers()).
//
// Re-run after changing a family, weight or style below:
//   node scripts/fonts/vendor-google-fonts.mjs
// It reaches into next's compiled loader, so a Next upgrade may move it; the
// output is plain files and keeps working regardless.

import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const FONT_DIR = join(APP, "public", "fonts");
const CSS_OUT = join(APP, "src", "app", "fonts.css");
const PRELOADS_OUT = join(APP, "src", "app", "fontPreloads.ts");

// What layout.tsx passed to next/font/google. `variable` is not carried
// over: globals.css owns --font-display / --font-sans / --font-mono, and its
// :root rules always won over the class next/font set on <html>.
const FONTS = [
  {
    loader: "Sora",
    slug: "sora",
    options: { subsets: ["latin"], weight: ["300", "400", "500", "600", "700", "800"], display: "swap", preload: true },
  },
  {
    loader: "DM_Sans",
    slug: "dm-sans",
    options: {
      subsets: ["latin"],
      weight: ["300", "400", "500", "600"],
      style: ["normal", "italic"],
      display: "swap",
      preload: true,
    },
  },
  {
    loader: "JetBrains_Mono",
    slug: "jetbrains-mono",
    options: { subsets: ["latin"], weight: ["400", "500"], display: "swap", preload: false },
  },
];

const require = createRequire(join(APP, "package.json"));
const googleLoader = require("next/dist/compiled/@next/font/dist/google/loader.js").default;

async function main() {
  rmSync(FONT_DIR, { recursive: true, force: true });
  mkdirSync(FONT_DIR, { recursive: true });

  const blocks = [];
  const preloads = [];
  for (const font of FONTS) {
    const result = await googleLoader({
      functionName: font.loader,
      data: [font.options],
      isDev: false,
      isServer: true,
      emitFontFile: (buffer, ext, preload) => {
        const hash = createHash("sha256").update(buffer).digest("hex").slice(0, 12);
        const name = `${font.slug}-${hash}.${ext}`;
        writeFileSync(join(FONT_DIR, name), buffer);
        const url = `/fonts/${name}`;
        if (preload && !preloads.includes(url)) preloads.push(url);
        return url;
      },
    });
    blocks.push(`/* ── ${font.loader.replace(/_/g, " ")} ── */\n${result.css.trim()}`);
  }

  const files = readdirSync(FONT_DIR).sort();
  writeFileSync(
    CSS_OUT,
    `/* GENERATED by scripts/fonts/vendor-google-fonts.mjs — do not edit by hand.
 *
 * The site's webfonts, self-hosted from public/fonts/ (${files.length} files).
 * These are the @font-face rules next/font/google used to produce at build
 * time, unchanged except that the files are already here. The custom
 * properties that pick a face (--font-display, --font-sans, --font-mono,
 * --font-latin) live in globals.css.
 */

${blocks.join("\n\n")}
`,
  );
  writeFileSync(
    PRELOADS_OUT,
    `// GENERATED by scripts/fonts/vendor-google-fonts.mjs — do not edit by hand.
//
// The font files next/font/google preloaded: the latin subset of every
// family that asked for \`preload: true\`. layout.tsx hands them to
// ReactDOM.preload, which emits the same <link rel="preload" as="font">.
export const FONT_PRELOADS: readonly string[] = ${JSON.stringify(preloads, null, 2)};
`,
  );
  console.log(`wrote ${files.length} font files, ${CSS_OUT}, ${PRELOADS_OUT} (${preloads.length} preloads)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
